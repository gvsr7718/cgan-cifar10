"""Fréchet Inception Distance (FID) computation module.

This module calculates the FID score between real CIFAR-10 test images
and class-conditioned synthetic images generated by the Generator. It extracts
deep feature representations using a pre-trained Inception-v3 model.
"""

from typing import Tuple

import numpy as np
import scipy.linalg
import torch
import torch.nn as nn
import torch.nn.functional as F
from torch.utils.data import DataLoader
from torchvision.models import inception_v3, Inception_V3_Weights

from src.models.generator import Generator


def calculate_activation_statistics(
    images: torch.Tensor,
    model: nn.Module,
    batch_size: int = 50,
    dims: int = 2048,
    device: torch.device = torch.device("cpu"),
) -> Tuple[np.ndarray, np.ndarray]:
    """Calculate the mean and covariance of activations for a set of images.

    Args:
        images: Tensor of shape [N, 3, H, W] with pixel values in [-1, 1].
        model: Pre-trained feature extractor (e.g., InceptionV3).
        batch_size: Batch size for feature extraction.
        dims: Dimensionality of the features.
        device: Device to run the extraction on.

    Returns:
        mu: Mean of the activations, shape [dims].
        sigma: Covariance matrix of the activations, shape [dims, dims].
    """
    model.eval()
    num_images = images.shape[0]
    activations = np.empty((num_images, dims))

    with torch.no_grad():
        for i in range(0, num_images, batch_size):
            start = i
            end = min(i + batch_size, num_images)
            batch = images[start:end].to(device)

            # Map from generator/real preprocessing range [-1, 1] to [0, 1]
            batch = (batch + 1.0) / 2.0

            # Resize to 299x299 as required by Inception-v3
            batch = F.interpolate(
                batch, size=(299, 299), mode="bilinear", align_corners=False
            )

            pred = model(batch)

            # Store the features
            activations[start:end] = pred.cpu().numpy()

    mu = np.mean(activations, axis=0)
    sigma = np.cov(activations, rowvar=False)

    return mu, sigma


def calculate_frechet_distance(
    mu1: np.ndarray,
    sigma1: np.ndarray,
    mu2: np.ndarray,
    sigma2: np.ndarray,
    eps: float = 1e-6,
) -> float:
    """Calculate the Fréchet Distance between two multivariate Gaussians.

    Args:
        mu1: Mean vector of the first distribution.
        sigma1: Covariance matrix of the first distribution.
        mu2: Mean vector of the second distribution.
        sigma2: Covariance matrix of the second distribution.
        eps: Small epsilon added to diagonal to prevent singularity.

    Returns:
        The Fréchet distance.
    """
    mu1 = np.atleast_1d(mu1)
    mu2 = np.atleast_1d(mu2)

    sigma1 = np.atleast_2d(sigma1)
    sigma2 = np.atleast_2d(sigma2)

    assert mu1.shape == mu2.shape, "Training and test mean vectors have different lengths."
    assert sigma1.shape == sigma2.shape, "Training and test covariances have different dimensions."

    diff = mu1 - mu2

    # Calculate the square root of the product of covariances
    covmean, _ = scipy.linalg.sqrtm(sigma1.dot(sigma2), disp=False)

    # Handle singular product
    if not np.isfinite(covmean).all():
        offset = np.eye(sigma1.shape[0]) * eps
        covmean = scipy.linalg.sqrtm((sigma1 + offset).dot(sigma2 + offset))

    # Handle complex numbers resulting from numerical errors
    if np.iscomplexobj(covmean):
        if not np.allclose(np.diagonal(covmean).imag, 0, atol=1e-3):
            m = np.max(np.abs(covmean.imag))
            raise ValueError(f"Imaginary component found in covmean: {m}")
        covmean = covmean.real

    tr_covmean = np.trace(covmean)

    return float(diff.dot(diff) + np.trace(sigma1) + np.trace(sigma2) - 2 * tr_covmean)


def compute_fid_score(
    generator: Generator,
    real_dataloader: DataLoader,
    num_images: int = 10000,
    device: torch.device = torch.device("cpu"),
) -> float:
    """Compute the FID score between real and generated images.

    Args:
        generator: Trained conditional Generator.
        real_dataloader: DataLoader containing real CIFAR-10 images.
        num_images: Total number of images to generate and evaluate.
        device: Device to run the computations on.

    Returns:
        The calculated FID score.
    """
    generator = generator.to(device)
    generator.eval()

    # Load pre-trained Inception-v3 model
    # aux_logits=True is required when loading DEFAULT weights
    inception = inception_v3(
        weights=Inception_V3_Weights.DEFAULT,
        transform_input=True,
    )
    # Remove the classification layer to extract the 2048-dim features
    inception.fc = nn.Identity()
    inception = inception.to(device)
    inception.eval()

    # 1. Collect real images
    real_images_list = []
    collected_real = 0
    for batch_imgs, _ in real_dataloader:
        batch_size = batch_imgs.size(0)
        if collected_real + batch_size > num_images:
            batch_imgs = batch_imgs[: num_images - collected_real]
            real_images_list.append(batch_imgs)
            break
        real_images_list.append(batch_imgs)
        collected_real += batch_size
        if collected_real >= num_images:
            break

    real_images = torch.cat(real_images_list, dim=0)

    # 2. Generate fake images
    fake_images_list = []
    num_classes = generator.num_classes
    latent_dim = generator.latent_dim

    collected_fake = 0
    batch_size = 100  # Batch size for generation

    with torch.no_grad():
        while collected_fake < num_images:
            curr_batch = min(batch_size, num_images - collected_fake)

            # Balance labels sequentially across classes
            labels = torch.arange(
                collected_fake, collected_fake + curr_batch
            ) % num_classes
            labels = labels.to(device)

            noise = torch.randn(curr_batch, latent_dim, device=device)
            fake_batch = generator(noise, labels)

            # Move to CPU immediately to save GPU memory
            fake_images_list.append(fake_batch.cpu())
            collected_fake += curr_batch

    fake_images = torch.cat(fake_images_list, dim=0)

    # 3. Calculate activation statistics
    mu_real, sigma_real = calculate_activation_statistics(
        real_images, inception, batch_size=50, dims=2048, device=device
    )

    mu_fake, sigma_fake = calculate_activation_statistics(
        fake_images, inception, batch_size=50, dims=2048, device=device
    )

    # 4. Calculate Fréchet distance
    fid = calculate_frechet_distance(mu_real, sigma_real, mu_fake, sigma_fake)

    return fid
