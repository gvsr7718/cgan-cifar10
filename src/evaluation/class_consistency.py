"""Class consistency evaluation for conditional GAN generation.

This module evaluates whether images generated by the cGAN correspond
to their requested CIFAR-10 class labels using an independent classifier.
"""

from typing import Dict, Tuple

import torch

from src.models.classifier import CIFAR10Classifier, predict
from src.models.generator import Generator


def compute_class_consistency_score(
    generator: Generator,
    classifier: CIFAR10Classifier,
    num_samples_per_class: int = 100,
    device: torch.device = torch.device("cpu"),
) -> float:
    """Calculate overall class consistency of generated images.

    For each CIFAR-10 class, synthetic images are generated using that
    class as the conditioning label. The independent classifier then
    predicts the class of each generated image.

    Args:
        generator: Trained conditional Generator.
        classifier: Independently trained CIFAR-10 classifier.
        num_samples_per_class: Number of generated images per class.
        device: Device used for evaluation.

    Returns:
        Fraction of generated images classified as their intended class.
        Value is between 0.0 and 1.0.
    """
    if num_samples_per_class <= 0:
        raise ValueError(
            "num_samples_per_class must be greater than zero."
        )

    generator = generator.to(device)
    classifier = classifier.to(device)

    generator.eval()
    classifier.eval()

    total_correct = 0
    total_samples = 0

    with torch.no_grad():
        for class_idx in range(generator.num_classes):
            labels = torch.full(
                (num_samples_per_class,),
                class_idx,
                dtype=torch.long,
                device=device,
            )

            noise = torch.randn(
                num_samples_per_class,
                generator.latent_dim,
                device=device,
            )

            generated_images = generator(noise, labels)

            predictions, _ = predict(
                classifier,
                generated_images,
            )

            total_correct += (
                predictions == labels
            ).sum().item()

            total_samples += num_samples_per_class

    return total_correct / total_samples


def compute_per_class_consistency(
    generator: Generator,
    classifier: CIFAR10Classifier,
    num_samples_per_class: int = 100,
    device: torch.device = torch.device("cpu"),
) -> Dict[int, float]:
    """Calculate class consistency separately for every class.

    Args:
        generator: Trained conditional Generator.
        classifier: Independently trained CIFAR-10 classifier.
        num_samples_per_class: Number of samples generated per class.
        device: Device used for evaluation.

    Returns:
        Dictionary mapping class index to consistency score.
    """
    if num_samples_per_class <= 0:
        raise ValueError(
            "num_samples_per_class must be greater than zero."
        )

    generator = generator.to(device)
    classifier = classifier.to(device)

    generator.eval()
    classifier.eval()

    consistency: Dict[int, float] = {}

    with torch.no_grad():
        for class_idx in range(generator.num_classes):
            labels = torch.full(
                (num_samples_per_class,),
                class_idx,
                dtype=torch.long,
                device=device,
            )

            noise = torch.randn(
                num_samples_per_class,
                generator.latent_dim,
                device=device,
            )

            generated_images = generator(noise, labels)

            predictions, _ = predict(
                classifier,
                generated_images,
            )

            correct = (
                predictions == labels
            ).sum().item()

            consistency[class_idx] = (
                correct / num_samples_per_class
            )

    return consistency


def compute_confusion_matrix(
    generator: Generator,
    classifier: CIFAR10Classifier,
    num_samples_per_class: int = 100,
    device: torch.device = torch.device("cpu"),
) -> torch.Tensor:
    """Generate a confusion matrix for conditional generation.

    Rows represent intended classes and columns represent classifier
    predictions.

    Args:
        generator: Trained conditional Generator.
        classifier: Independently trained CIFAR-10 classifier.
        num_samples_per_class: Number of samples per intended class.
        device: Device used for evaluation.

    Returns:
        Integer tensor of shape [num_classes, num_classes].
    """
    if num_samples_per_class <= 0:
        raise ValueError(
            "num_samples_per_class must be greater than zero."
        )

    generator = generator.to(device)
    classifier = classifier.to(device)

    generator.eval()
    classifier.eval()

    num_classes = generator.num_classes

    confusion = torch.zeros(
        num_classes,
        num_classes,
        dtype=torch.long,
    )

    with torch.no_grad():
        for class_idx in range(num_classes):
            labels = torch.full(
                (num_samples_per_class,),
                class_idx,
                dtype=torch.long,
                device=device,
            )

            noise = torch.randn(
                num_samples_per_class,
                generator.latent_dim,
                device=device,
            )

            generated_images = generator(noise, labels)

            predictions, _ = predict(
                classifier,
                generated_images,
            )

            for predicted_class in predictions.cpu():
                confusion[
                    class_idx,
                    predicted_class.item(),
                ] += 1

    return confusion


def consistency_report(
    generator: Generator,
    classifier: CIFAR10Classifier,
    num_samples_per_class: int = 100,
    device: torch.device = torch.device("cpu"),
) -> Tuple[float, Dict[int, float], torch.Tensor]:
    """Compute overall score, per-class scores, and confusion matrix.

    Returns:
        Tuple containing:
            overall_score: Overall class consistency.
            per_class_scores: Consistency for each class.
            confusion_matrix: Intended-vs-predicted class counts.
    """
    overall_score = compute_class_consistency_score(
        generator=generator,
        classifier=classifier,
        num_samples_per_class=num_samples_per_class,
        device=device,
    )

    per_class_scores = compute_per_class_consistency(
        generator=generator,
        classifier=classifier,
        num_samples_per_class=num_samples_per_class,
        device=device,
    )

    confusion = compute_confusion_matrix(
        generator=generator,
        classifier=classifier,
        num_samples_per_class=num_samples_per_class,
        device=device,
    )

    return (
        overall_score,
        per_class_scores,
        confusion,
    )